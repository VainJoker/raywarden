//! HTTP response wrappers for successful application results.
use axum::{
    Json,
    response::{
        IntoResponse,
        Response,
    },
};
use serde::Serialize;

/// Serialize the response body as JSON using its public wire format.
pub(in crate::api) struct ApiResponse<T>(pub T);

impl<T: Serialize> IntoResponse for ApiResponse<T> {
    fn into_response(self) -> Response {
        Json(self.0).into_response()
    }
}

#[derive(Serialize)]
pub(in crate::api) struct EmptyObject {}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub(in crate::api) struct EmptyListResponse {
    data:               [(); 0],
    object:             &'static str,
    continuation_token: (),
}

impl EmptyListResponse {
    pub(in crate::api) const fn new() -> Self {
        Self {
            data:               [],
            object:             "list",
            continuation_token: (),
        }
    }
}

/// JSON already generated by D1 or serde, without parsing it a second time.
pub struct RawJson(pub String);

impl IntoResponse for RawJson {
    fn into_response(self) -> Response {
        (
            [(axum::http::header::CONTENT_TYPE, "application/json")],
            self.0,
        )
            .into_response()
    }
}

#[cfg(test)]
mod tests {
    use std::{
        future::Future as _,
        task::{
            Context,
            Poll,
            Waker,
        },
    };

    use axum::http::StatusCode;
    use serde_json::{
        Value,
        json,
    };

    use super::*;

    fn body(response: Response) -> (StatusCode, Vec<u8>) {
        let status = response.status();
        let mut body = std::pin::pin!(axum::body::to_bytes(
            response.into_body(),
            usize::MAX
        ));
        let Poll::Ready(bytes) =
            body.as_mut().poll(&mut Context::from_waker(Waker::noop()))
        else {
            panic!("fixed JSON/string responses must be ready without I/O");
        };
        (status, bytes.expect("valid response fixture").to_vec())
    }

    #[test]
    fn typed_success_preserves_json_shape_and_status() {
        let response =
            (StatusCode::CREATED, ApiResponse(EmptyListResponse::new()))
                .into_response();
        assert_eq!(
            response.headers()[axum::http::header::CONTENT_TYPE],
            "application/json"
        );
        let (status, bytes) = body(response);
        assert_eq!(status, StatusCode::CREATED);
        assert_eq!(
            serde_json::from_slice::<Value>(&bytes)
                .expect("valid response fixture"),
            json!({"data":[],"object":"list","continuationToken":null})
        );
        assert_eq!(body(ApiResponse(()).into_response()).1, b"null");
        assert_eq!(body(ApiResponse(EmptyObject {}).into_response()).1, b"{}");
    }

    #[test]
    fn raw_json_keeps_its_body_bytes_and_content_type() {
        let value = " {\"data\":[1,2],\"object\":\"list\"}\n";
        let response = RawJson(value.into()).into_response();
        assert_eq!(
            response.headers()[axum::http::header::CONTENT_TYPE],
            "application/json"
        );
        let (status, bytes) = body(response);
        assert_eq!(status, StatusCode::OK);
        assert_eq!(bytes, value.as_bytes());
    }
}
